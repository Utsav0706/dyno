"""Production failures (JSONL) -> new Dyno cases (`dyno import-failures`).

Each line is one answer that went wrong in production: a thumbs-down in Scout, a low
judge score Pitwall logged, and so on. Only `input` is required:

    {"id": "opt", "input": "the question", "output": "what the agent said",
     "expected": "opt: answer or [key points]", "reason": "opt: why it was bad",
     "tags": ["opt"], "source": "opt: e.g. scout-feedback"}

Case ids default to prod-<first 8 hex of sha256(normalised input)>, so the same failure
imported twice gives the same case and duplicates collapse. A case without `expected`
can still be judged by quality and hallucination (task_rubric skips it). `output` and
`reason` aren't case fields: they describe the old answer, not what a good one is, so
they're kept only as a YAML comment above the case for whoever writes the key later.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict

from dyno.cases import Case


class ProductionFailure(BaseModel):
    model_config = ConfigDict(extra="ignore")  # producers may add fields; we read ours

    id: str | None = None
    input: str
    output: str | None = None
    expected: str | list[str] | None = None
    reason: str | None = None
    tags: list[str] = []
    source: str | None = None


def _norm(text: str) -> str:
    return " ".join(text.casefold().split())


def case_id(failure: ProductionFailure) -> str:
    if failure.id:
        return re.sub(r"[^A-Za-z0-9_.-]+", "-", failure.id).strip("-")[:100] or "prod"
    return "prod-" + hashlib.sha256(_norm(failure.input).encode()).hexdigest()[:8]


def read_failures(path: Path) -> list[ProductionFailure]:
    out = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            out.append(ProductionFailure.model_validate(json.loads(line)))
        except ValueError as exc:
            raise ValueError(f"{path}:{n}: {exc}") from exc
    return out


def to_cases(
    failures: list[ProductionFailure], existing_inputs: set[str] | None = None
) -> tuple[list[tuple[Case, ProductionFailure]], int]:
    """New cases (with the failure each came from) and how many were dropped as repeats."""
    seen = {_norm(i) for i in existing_inputs or set()}
    out, dropped = [], 0
    for f in failures:
        key = _norm(f.input)
        if not key or key in seen:
            dropped += 1
            continue
        seen.add(key)
        tags = ["production", *f.tags, *([f.source] if f.source else [])]
        case = Case(
            id=case_id(f), input=f.input, expected=f.expected, tags=list(dict.fromkeys(tags))
        )
        out.append((case, f))
    return out, dropped


def write_cases(pairs: list[tuple[Case, ProductionFailure]], out: Path) -> None:
    lines = ["# Generated by `dyno import-failures` from production failures.", "cases:"]
    for case, f in pairs:
        for label, value in (("was", f.output), ("why", f.reason)):
            if value:
                lines.append(f"  # {label}: {' '.join(value.split())[:200]}")
        data = case.model_dump(exclude_defaults=True)
        block = yaml.safe_dump([data], sort_keys=False, allow_unicode=True, width=100)
        lines += ["  " + ln for ln in block.rstrip("\n").splitlines()]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
