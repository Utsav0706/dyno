"""Turn Gearbox's held-out test prompts into a Dyno case file.

    py scripts/gearbox_suite.py GEARBOX_DIR OUT_FILE
    dyno run suites/gearbox.yaml --cases OUT_FILE

Reads data/v2/prompts.jsonl and the test ids in data/v2/split.json (119 prompts the
router never trained on). The prompts come from public benchmarks under their own
licences (see Gearbox's data/v2/README.md), so they stay in the Gearbox repo: write the
output under runs/ (gitignored), not into this repo.

A "gold" reference becomes the case's expected answer (one key point for task_rubric).
"example" references are just one good answer to an open-ended prompt, not a key, so
those prompts (and ones with no reference) get no expected answer and are judged on
quality alone. Tags: task type, source and difficulty, for the report's per-tag table.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml


def main(gearbox_dir: Path, out_file: Path) -> None:
    data = gearbox_dir / "data" / "v2"
    test_ids = set(json.loads((data / "split.json").read_text(encoding="utf-8"))["test"])
    cases = []
    for line in (data / "prompts.jsonl").read_text(encoding="utf-8").splitlines():
        row = json.loads(line)
        if row["id"] not in test_ids:
            continue
        case = {
            "id": row["id"],
            "input": row["prompt"],
            "tags": [row["task_type"], row["source"], row["difficulty"]],
        }
        if row.get("reference_kind") == "gold" and row.get("reference"):
            case["expected"] = str(row["reference"])
        cases.append(case)
    if len(cases) != len(test_ids):
        sys.exit(f"found {len(cases)} of {len(test_ids)} test prompts")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/gearbox_suite.py from Gearbox's data/v2 test split.\n"
    body = yaml.safe_dump({"cases": cases}, sort_keys=False, allow_unicode=True, width=100)
    out_file.write_text(header + body, encoding="utf-8")
    with_key = sum("expected" in c for c in cases)
    print(f"{len(cases)} cases ({with_key} with a gold answer) -> {out_file}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), Path(sys.argv[2]))
