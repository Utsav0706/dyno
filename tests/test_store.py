from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, text

from dyno.agents.example import ExampleAgent
from dyno.cases import Suite
from dyno.runner import run_suite
from dyno.store import open_engine
from dyno.store.db import alembic_config


def test_migration_creates_tables(db_url):
    engine = open_engine(db_url)
    tables = set(inspect(engine).get_table_names())
    assert {"runs", "cases", "results", "steps", "alembic_version"} <= tables
    open_engine(db_url)  # opening again is a no-op upgrade, not an error


def test_models_match_migrations(db_url):
    """Fails if a model changes without a migration (what `alembic check` does)."""
    open_engine(db_url)
    try:
        command.check(alembic_config(db_url))
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - message is the point
        raise AssertionError(f"models and migrations differ: {exc}") from exc


def test_deleting_a_run_cascades(store):
    suite = Suite.model_validate({"cases": [{"id": "a", "input": "2 + 2"}]})
    s = run_suite(suite, ExampleAgent(), agent_name="example", k=2, store=store)
    with store.engine.begin() as conn:
        conn.execute(text("DELETE FROM runs WHERE id = :id"), {"id": s.run_id})
        for table in ("cases", "results", "steps"):
            assert conn.execute(text(f"SELECT COUNT(*) FROM {table}")).scalar() == 0
